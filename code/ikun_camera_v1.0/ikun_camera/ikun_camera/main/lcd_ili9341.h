#ifndef LCD_ILI9341_H
#define LCD_ILI9341_H

#include <stdint.h>
#include "esp_err.h"

/**
 * @defgroup lcd_ili9341 ILI9341 LCD Driver
 * @brief Driver for ILI9341 2.4-inch TFT LCD panel (direct SPI, no esp_lcd)
 *
 * This driver uses driver/spi_master.h directly with manual DC/CS GPIO control,
 * replicating the verified CH32 LCD_Init() sequence. MADCTL=0x68 sets BGR=1
 * so the ILI9341 hardware matches the panel's B-G-R sub-pixel order — no
 * software channel swap is needed.
 *
 * @{
 */

/** @brief SPI host for LCD communication */
#define LCD_HOST SPI2_HOST

/** @brief GPIO pin for SPI clock */
#define PIN_NUM_SCLK 36
/** @brief GPIO pin for SPI MOSI (data out) */
#define PIN_NUM_MOSI 35
/** @brief GPIO pin for chip select */
#define PIN_NUM_CS 38
/** @brief GPIO pin for data/command selection */
#define PIN_NUM_DC 39
/** @brief GPIO pin for reset */
#define PIN_NUM_RST 40
/** @brief GPIO pin for backlight control */
#define PIN_NUM_BCKL 37

/** @brief LCD screen width in pixels (landscape) */
#define LCD_WIDTH 320
/** @brief LCD screen height in pixels (landscape) */
#define LCD_HEIGHT 240

/**
 * @brief Byte order of Image2Lcd exported pixel data.
 *
 * Set to 1 when Image2Lcd "MSB first" is enabled (high byte of each
 * 16-bit pixel stored first). Set to 0 when "MSB first" is disabled.
 */
#ifndef IMAGE2LCD_MSB_FIRST
#define IMAGE2LCD_MSB_FIRST 1
#endif

/**
 * @brief No-op color conversion (kept for API compatibility).
 *
 * This panel's R/B sub-pixel mapping is handled in hardware by MADCTL BGR=1,
 * so no software channel swap is needed. swap_gb() is kept as a no-op so
 * that thermal_display.c (which calls it) compiles unchanged.
 *
 * @param[in] c Standard RGB565 pixel value.
 * @return uint16_t The same pixel value, unchanged.
 */
static inline uint16_t swap_gb(uint16_t c)
{
    return c;
}

/**
 * @brief Initialize the LCD display subsystem.
 *
 * Initializes the SPI bus (spi_master), configures DC/CS/RST/BL GPIOs,
 * performs hardware reset, sends the full ILI9341 init sequence (copied
 * from the verified CH32 LCD_Init), and turns on the backlight.
 */
void lcd_init(void);

/**
 * @brief Fill the entire screen with a single color.
 *
 * @param[in] color RGB565 color value to fill the screen with.
 */
void fill_screen(uint16_t color);

/**
 * @brief Fill a rectangular area with a single color.
 *
 * @param[in] x1 Starting X coordinate of the rectangle.
 * @param[in] y1 Starting Y coordinate of the rectangle.
 * @param[in] x2 Ending X coordinate of the rectangle (exclusive).
 * @param[in] y2 Ending Y coordinate of the rectangle (exclusive).
 * @param[in] color RGB565 color value to fill the rectangle with.
 */
void fill_rect(int x1, int y1, int x2, int y2, uint16_t color);

/**
 * @brief Draw a bitmap of RGB565 color data to a rectangular area.
 *
 * Sends a pixel buffer to the specified rectangle. The buffer must contain
 * (x2 - x1) * (y2 - y1) pixels in standard RGB565 format. Byte-order
 * conversion to big-endian (panel requirement) is handled internally.
 *
 * @param[in] x1 Starting X coordinate of the rectangle.
 * @param[in] y1 Starting Y coordinate of the rectangle.
 * @param[in] x2 Ending X coordinate of the rectangle (exclusive).
 * @param[in] y2 Ending Y coordinate of the rectangle (exclusive).
 * @param[in] color_data Pointer to the RGB565 color data buffer.
 */
void lcd_draw_bitmap(int x1, int y1, int x2, int y2, const uint16_t *color_data);

/**
 * @brief Push a raw big-endian RGB565 frame to a rectangular area (zero-copy).
 *
 * Transmits the caller's buffer directly in a single SPI transaction —
 * no intermediate DMA buffer, no byte swap. Intended for camera preview:
 * the esp32-camera RGB565 framebuffer is already big-endian in memory,
 * which is exactly the on-the-wire byte order the ILI9341 expects.
 *
 * @param[in] x1   Starting X coordinate of the window.
 * @param[in] y1   Starting Y coordinate of the window.
 * @param[in] x2   Ending X coordinate of the window (exclusive).
 * @param[in] y2   Ending Y coordinate of the window (exclusive).
 * @param[in] data Pointer to (x2-x1)*(y2-y1)*2 bytes of big-endian RGB565.
 * @param[in] len  Number of bytes in @p data.
 */
void lcd_write_frame(int x1, int y1, int x2, int y2,
                     const uint8_t *data, size_t len);

/**
 * @brief Draw a 16-bit image exported by Image2Lcd.
 *
 * Renders a color bitmap generated by Image2Lcd v2.9 with vertical scan
 * mode and 16-bit true color output. The 8-byte header is auto-detected.
 *
 * @param[in] x Starting X coordinate (left edge of the image).
 * @param[in] y Starting Y coordinate (top edge of the image).
 * @param[in] image_data Pointer to the Image2Lcd exported C array.
 * @param[in] w Image width in pixels (fallback when header absent).
 * @param[in] h Image height in pixels (fallback when header absent).
 * @return esp_err_t ESP_OK on success, ESP_ERR_INVALID_ARG on invalid input.
 */
esp_err_t lcd_draw_image2lcd(int x, int y, const uint8_t *image_data,
                             int w, int h);

/**
 * @brief Draw a 16-bit Image2Lcd bitmap upside down on screen.
 *
 * The on-screen result is rotated 180 degrees versus lcd_draw_image2lcd()
 * (equivalent to 90 degrees clockwise from the source data). Intended for
 * square images such as the boot logo.
 *
 * @param[in] x Starting X coordinate (left edge of the image).
 * @param[in] y Starting Y coordinate (top edge of the image).
 * @param[in] image_data Pointer to the Image2Lcd exported C array.
 * @param[in] w Image width in pixels (fallback when header absent).
 * @param[in] h Image height in pixels (fallback when header absent).
 * @return esp_err_t ESP_OK on success, ESP_ERR_INVALID_ARG on invalid input.
 */
esp_err_t lcd_draw_image2lcd_180(int x, int y, const uint8_t *image_data,
                                 int w, int h);
                             
/** @} */

/**
 * @brief Draw a single point on LCD
 * @param x     X coordinate
 * @param y     Y coordinate
 * @param color Point color
 */
void LCD_DrawPoint(uint16_t x, uint16_t y, uint16_t color);

/**
 * @brief Display 16*16 ASCII and GBK Chinese font on LCD
 * @param x      Start X coordinate of text
 * @param y      Start Y coordinate of text
 * @param fc     Foreground color (RGB565)
 * @param bc     Background color (RGB565)
 * @param s      Pointer to string buffer, support ASCII + GBK encoding
 * @note  Newline character '\n' is supported for line feed
 */
void Gui_DrawFont_GBK16(uint16_t x, uint16_t y, uint16_t fc, uint16_t bc, uint8_t *s);

/**
 * @brief Display 16*16 ASCII and GBK Chinese font on LCD (transparent background)
 *
 * Only draws foreground pixels. Background pixels are left unchanged, so the
 * text appears overlaid on whatever is already on screen. Useful for drawing
 * labels on top of images or thermal data without erasing them.
 *
 * @param[in] x  Start X coordinate of text
 * @param[in] y  Start Y coordinate of text
 * @param[in] fc Foreground color (RGB565)
 * @param[in] s  Pointer to string buffer (ASCII + GBK encoding, '\n' supported)
 */
void lcd_draw_text(int x, int y, uint16_t fc, const uint8_t *s);

/**
 * @brief Display text with a solid background (flicker-free overlay)
 *
 * Renders text into an off-screen buffer (background color filled first,
 * then foreground pixels overwritten) and transmits the whole text box to
 * the panel in a single SPI transaction. Because the entire region is
 * repainted atomically each call, there is no flicker and no residual
 * digits from the previous frame - suitable for dynamic values (e.g. live
 * temperature readouts) displayed on top of a changing background.
 *
 * @param[in] x  Start X coordinate of text box
 * @param[in] y  Start Y coordinate of text box
 * @param[in] fc Foreground color (RGB565)
 * @param[in] bg Background color (RGB565), fills the whole text box
 * @param[in] s  Pointer to string buffer (ASCII + GBK, '\n' supported)
 */
void lcd_draw_text_bg(int x, int y, uint16_t fc, uint16_t bg, const uint8_t *s);

/**
 * @brief Draw a battery level icon (flicker-free, single SPI transaction)
 *
 * Renders a 40x16 pixel battery icon at (x,y): white outline, colored fill
 * bar proportional to level. Fill color: red <30%, yellow <60%, green >=60%.
 * The whole icon is composed in an off-screen DMA buffer and sent in one
 * SPI transaction so it updates atomically — no flicker.
 *
 * @param[in] x     Top-left X on screen
 * @param[in] y     Top-left Y on screen
 * @param[in] level Battery level 0-100 (clamped)
 */
void lcd_draw_battery(int x, int y, int level);

/**
 * @brief Flicker-free text overlay with fixed box size and reusable buffer
 *
 * Designed for frequently-refreshed numeric overlays (e.g. temperature
 * readouts). The caller specifies the exact box dimensions; all text
 * segments passed via a NULL-terminated vararg list of (ox, oy, string)
 * are rendered into the same off-screen buffer, and the whole box is
 * transmitted to the panel in exactly one SPI transaction. A single
 * static DMA-capable buffer is reused across calls to avoid per-frame
 * heap allocations. Combined with a fixed-width numeric format
 * (e.g. "%+06.1f") this achieves fully flicker-free updates.
 *
 * @param[in] x  Top-left X of the fixed box on screen
 * @param[in] y  Top-left Y of the fixed box on screen
 * @param[in] w  Width of the box in pixels
 * @param[in] h  Height of the box in pixels
 * @param[in] fc Foreground color (RGB565)
 * @param[in] bg Background color (RGB565)
 * @param[in] ... Triplets of (int ox, int oy, const uint8_t *str) terminated
 *                by a single negative int (e.g. -1). The sentinel must be a
 *                negative ox so the parser can stop after reading only one
 *                argument without touching the stack for oy/str.
 *
 * Example:
 *   lcd_draw_text_fixed(10, 10, 80, 46, 0xFFFF, 0x0000,
 *       0,  0, (const uint8_t *)"MIN:23.5",
 *       0, 20, (const uint8_t *)"MAX:87.2",
 *       -1);
 */
void lcd_draw_text_fixed(int x, int y, int w, int h,
                         uint16_t fc, uint16_t bg, ...);

#endif /* LCD_ILI9341_H */
